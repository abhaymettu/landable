// Scores repos through the endpoint and the CLI at the same commit, and writes analysis/agreement.md.
// usage: node study/agreement.mjs <endpoint base URL> [output name in analysis/]   (run pnpm run build first)
import { readFileSync, writeFileSync } from "node:fs";
import { snap } from "../dist/providers.js";
import { evaluate } from "../dist/score.js";

const base = process.argv[2];
if (!base) throw new Error("usage: node study/agreement.mjs <endpoint base URL>");
const fixtures = readFileSync(new URL("../test/fixtures/NOTICE.md", import.meta.url), "utf8")
  .split("\n")
  .map((l) => /^\| ([\w.-]+\/[\w.-]+) \|/.exec(l)?.[1])
  .filter((r) => r !== undefined);
const top = readFileSync(new URL("../data/frozen/top-meta.jsonl", import.meta.url), "utf8")
  .trim()
  .split("\n")
  .map((l) => JSON.parse(l))
  .filter((r) => r.rank <= 50 && !r.archived && !fixtures.includes(r.name_now))
  .sort((a, b) => a.rank - b.rank)
  .slice(0, 20 - fixtures.length)
  .map((r) => r.name_now);

const rows = [];
for (const repo of [...fixtures, ...top]) {
  let res, ms;
  for (;;) {
    const t0 = performance.now();
    res = await fetch(`${base}/api/score?repo=${repo}`);
    ms = Math.round(performance.now() - t0);
    if (res.status !== 429) break;
    await new Promise((r) => setTimeout(r, 61_000));
  }
  const body = await res.json();
  if (!res.ok) {
    rows.push({ repo, ms, error: `${res.status} ${body.error}` });
    continue;
  }
  const [owner, name] = repo.split("/");
  const cli = evaluate((await snap({ kind: "github", owner, repo: name, ref: body.commit })).snapshot);
  const differ = body.items.filter((i) => {
    const f = cli.findings.get(i.id);
    return f === undefined || f.value !== i.value || f.evidence.join("\n") !== i.evidence.join("\n");
  });
  rows.push({ repo, ms, cached: body.cached, commit: body.commit.slice(0, 12), partial: body.partial, differ: differ.map((i) => i.id), market: JSON.stringify(cli.market) === JSON.stringify(body.market) });
  console.log(repo, ms, differ.length, body.partial ? "partial" : "");
}

const cold = rows.filter((r) => r.error === undefined && r.cached === false).map((r) => r.ms).sort((a, b) => a - b);
const pct = (p) => cold[Math.min(cold.length - 1, Math.ceil(p * cold.length) - 1)];
const ok = rows.filter((r) => r.error === undefined);
const full = ok.filter((r) => r.differ.length === 0 && r.market);
const lines = [
  "# Endpoint and CLI agreement",
  "",
  `Generated by \`node study/agreement.mjs ${base}\` on ${new Date().toISOString().slice(0, 10)}. Each repo is scored by the endpoint at its latest commit, then by the CLI at that same commit; a repo agrees when all item values, their evidence and the market scores match.`,
  "",
  `- Agree in full: ${full.length} of ${rows.length}. Errors: ${rows.length - ok.length}.`,
  `- Endpoint latency, uncached calls (${cold.length}): median ${pct(0.5)} ms, p95 ${pct(0.95)} ms, measured from the caller.`,
  "",
  "| Repo | Commit | Items that differ | Market scores match | Read in part | Latency (ms) |",
  "|---|---|---|---|---|---|",
  ...rows.map((r) =>
    r.error !== undefined
      ? `| ${r.repo} | | ${r.error} | | | ${r.ms} |`
      : `| ${r.repo} | ${r.commit} | ${r.differ.length === 0 ? "none" : r.differ.join(", ")} | ${r.market ? "yes" : "no"} | ${r.partial ? `${r.partial.read} of ${r.partial.wanted} texts${r.partial.truncatedTree ? ", tree cut" : ""}` : "no"} | ${r.ms}${r.cached ? " (cached)" : ""} |`,
  ),
  "",
];
writeFileSync(new URL(`../analysis/${process.argv[3] ?? "agreement.md"}`, import.meta.url), lines.join("\n"));
console.log(lines.slice(4, 6).join("\n"));
